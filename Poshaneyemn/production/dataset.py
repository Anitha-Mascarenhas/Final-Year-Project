"""Child-level dataset assembly for the production hybrid pipeline.

Merges the labeled AnthroVision table with the pre-extracted MediaPipe CV features and
DeepLabV3+ segmentation features (both produced by the existing extraction code), and
loads the frozen child-level train/validation/test splits generated by
``experiments/cv_multimodal_baseline`` so that no child appears in two splits.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field

import numpy as np
import pandas as pd

from .config import (
    ANTHROVISION_CSV,
    CV_FEATURES_CSV,
    CLASS_TO_INDEX,
    FROZEN_SPLITS_JSON,
    SEG_FEATURES_CSV,
    TARGET_COLUMN,
)


@dataclass
class HybridDataset:
    """Child-level dataframe plus the three split index sets (child ids)."""

    df: pd.DataFrame
    train_child_ids: list[int] = field(default_factory=list)
    validation_child_ids: list[int] = field(default_factory=list)
    test_child_ids: list[int] = field(default_factory=list)

    def split(self, name: str) -> pd.DataFrame:
        ids = {
            "train": self.train_child_ids,
            "validation": self.validation_child_ids,
            "test": self.test_child_ids,
        }[name]
        return self.df[self.df["child_id"].isin(ids)].reset_index(drop=True)

    def assert_disjoint_splits(self) -> None:
        tr = set(self.train_child_ids)
        va = set(self.validation_child_ids)
        te = set(self.test_child_ids)
        assert not (tr & va), "Train and validation children overlap"
        assert not (tr & te), "Train and test children overlap (data leakage)"
        assert not (va & te), "Validation and test children overlap (data leakage)"
        assert len(tr | va | te) == len(tr) + len(va) + len(te)


def _load_frontal1_cv_features() -> pd.DataFrame:
    cv = pd.read_csv(CV_FEATURES_CSV)
    cv = cv[cv["view"] == "frontal1"].copy()
    cv["image_name"] = cv["image_name"].astype(str)
    return cv


def _load_segmentation_features() -> pd.DataFrame:
    seg = pd.read_csv(SEG_FEATURES_CSV)
    seg["child_id"] = pd.to_numeric(seg["child_id"], errors="coerce").astype("Int64")
    keep = ["child_id"] + [c for c in seg.columns if c not in {"child_id", "tag", "view", "image_name", "shoulder_width_ref"}]
    seg = seg[keep].drop_duplicates(subset=["child_id"], keep="first")
    return seg


def build_dataset() -> HybridDataset:
    """Load, merge, derive and label the child-level multimodal dataset."""
    anthro = pd.read_csv(ANTHROVISION_CSV)
    anthro = anthro.loc[:, ~anthro.columns.str.contains(r"^Unnamed")]
    anthro = anthro.dropna(subset=[TARGET_COLUMN]).drop_duplicates(subset=["tag"], keep="first").copy()
    anthro["child_id"] = pd.to_numeric(anthro["tag"], errors="coerce").astype("Int64")
    anthro = anthro.dropna(subset=["child_id"])

    # frontal1 filename -> used to join the MediaPipe CV features (keyed by image name)
    anthro["f1_filename"] = anthro["image_path_frontal1"].dropna().apply(lambda p: str(p).replace("\\", "/").split("/")[-1])

    cv = _load_frontal1_cv_features()
    seg = _load_segmentation_features()

    df = anthro.merge(cv, left_on="f1_filename", right_on="image_name", how="inner")
    df = df.merge(seg, on="child_id", how="inner")

    # --- anthropometric columns -------------------------------------------------
    df = df.rename(columns={"Age": "age_months", "Height": "height_cm", "Weight": "weight_kg",
                            "HC": "head_circumference_cm", "MUAC": "muac_cm"})
    df["age_months"] = pd.to_numeric(df["age_months"], errors="coerce")
    df["height_cm"] = pd.to_numeric(df["height_cm"], errors="coerce")
    df["weight_kg"] = pd.to_numeric(df["weight_kg"], errors="coerce")
    df["head_circumference_cm"] = pd.to_numeric(df["head_circumference_cm"], errors="coerce")
    df["muac_cm"] = pd.to_numeric(df["muac_cm"], errors="coerce")
    df["gender_male"] = df["Gender"].astype(str).str.upper().map({"M": 1.0, "F": 0.0})
    df["waist_cm"] = np.nan  # reserved slot (see config.WAIST_COLUMN note)

    # Derived anthropometric feature: BMI recomputed from height/weight when missing.
    df["bmi"] = pd.to_numeric(df.get("BMI"), errors="coerce")
    recompute = df["bmi"].isna() & df["height_cm"].notna() & (df["height_cm"] > 0) & df["weight_kg"].notna()
    df.loc[recompute, "bmi"] = df.loc[recompute, "weight_kg"] / (df.loc[recompute, "height_cm"] / 100.0) ** 2

    # --- label -------------------------------------------------------------------
    df["label"] = df[TARGET_COLUMN].astype(str).map(CLASS_TO_INDEX)
    df = df.dropna(subset=["label"]).reset_index(drop=True)
    df["label"] = df["label"].astype(int)

    for col in ["image_name", "tag_y", "view_y"]:
        if col in df.columns:
            df = df.rename(columns={col: f"seg_{col}" if col in {"tag_y", "view_y"} else col})

    dataset = HybridDataset(df=df)
    _apply_frozen_splits(dataset)
    dataset.df = dataset.df[dataset.df["child_id"].isin(
        dataset.train_child_ids + dataset.validation_child_ids + dataset.test_child_ids
    )].reset_index(drop=True)
    dataset.assert_disjoint_splits()
    return dataset


def _apply_frozen_splits(dataset: HybridDataset) -> None:
    with open(FROZEN_SPLITS_JSON, "r", encoding="utf-8") as fh:
        info = json.load(fh)
    ids = info["child_ids"]
    dataset.train_child_ids = [int(c) for c in ids["train"]]
    dataset.validation_child_ids = [int(c) for c in ids["validation"]]
    dataset.test_child_ids = [int(c) for c in ids["test"]]


if __name__ == "__main__":
    ds = build_dataset()
    print("children:", ds.df["child_id"].nunique(), "rows:", len(ds.df))
    print("train/val/test:", len(ds.train_child_ids), len(ds.validation_child_ids), len(ds.test_child_ids))
    print("label distribution:", ds.df["label"].value_counts().sort_index().to_dict())
    print("split sizes:", {k: len(ds.split(k)) for k in ("train", "validation", "test")})
