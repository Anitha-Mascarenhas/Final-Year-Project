def test_private_child_records_are_not_automatically_attached_to_chat():
    payload = ChatRequest(message="What is the latest result?", language="en")
    messages = _messages_for(payload)
    joined = "\n".join(message["content"] for message in messages)
    assert "Child records are unavailable unless" in joined
    assert all("child_id" not in message["content"] for message in messages)
    assert all("screening_history" not in message["content"] for message in messages)


def test_child_records_only_loaded_for_parent_selected_screen(monkeypatch):
    import asyncio
    from routers import assistant

    async def should_not_read(_child_id):
        raise AssertionError("unauthorized child record lookup")

    monkeypatch.setattr(assistant, "get_child_by_id", should_not_read)
    payload = ChatRequest(
        message="What is my child's latest result?", screen="results", child_id="child-b"
    )
    context = asyncio.run(
        assistant._verified_child_context(payload, {"user_id": "child-a", "role": "parent"})
    )
    assert context is None


def test_child_context_returns_only_requested_measurement_without_identifier(monkeypatch):
    import asyncio
    from routers import assistant

    async def child(_child_id):
        return {"childId": "child-a", "childName": "Private Name"}

    async def history(_child_id):
        return [{
            "childId": "child-a",
            "prediction": "underweight",
            "vitals": {"weight_kg": 12.5, "height_cm": 91.0, "gender": "female"},
        }]

    monkeypatch.setattr(assistant, "get_child_by_id", child)
    monkeypatch.setattr(assistant, "fetch_screening_history", history)
    payload = ChatRequest(
        message="What was my child's weight?", screen="results", child_id="child-a"
    )
    context = asyncio.run(
        assistant._verified_child_context(payload, {"user_id": "child-a", "role": "parent"})
    )
    assert '"latest_model_screening_label": "underweight"' in context
    assert '"weight_kg": 12.5' in context
    assert "height_cm" not in context
    assert "female" not in context
    assert "child-a" not in context
    assert "Private Name" not in context


def test_nutrition_context_uses_selected_region_rule_without_sending_region(monkeypatch):
    import asyncio
    from routers import assistant

    async def child(_child_id):
        return {"childId": "child-a", "childName": "Private Name"}

    async def history(_child_id):
        return [{
            "childId": "child-a",
            "screening_result": {"prediction": "underweight"},
            "vitals": {"age_years": 2, "age_months": 0},
        }]

    monkeypatch.setattr(assistant, "get_child_by_id", child)
    monkeypatch.setattr(assistant, "fetch_screening_history", history)
    payload = ChatRequest(
        message="Why was ragi recommended on this plan?",
        screen="nutrition",
        child_id="child-a",
        nutrition_region={"state": "Karnataka"},
    )
    context = asyncio.run(
        assistant._verified_child_context(payload, {"user_id": "child-a", "role": "parent"})
    )
    assert '"food": "ragi"' in context
    assert "Karnataka" not in context
    assert "Private Name" not in context


def test_follow_up_keeps_bounded_conversation_and_retrieves_for_current_question():
    payload = ChatRequest(
        message="Can you make that simpler?",
        history=[{"role": "user", "content": "What is stunting?"},
                 {"role": "assistant", "content": "Low height for age."}],
    )
    messages = _messages_for(payload)
    assert messages[-3:] == [
        {"role": "user", "content": "What is stunting?"},
        {"role": "assistant", "content": "Low height for age."},
        {"role": "user", "content": "Can you make that simpler?"},
    ]
