from knowledge.retrieval import retrieve_knowledge
from routers.assistant import ChatRequest, _messages_for


def test_pipeline_answer_retrieves_real_model_components_and_scope():
    knowledge, _ = retrieve_knowledge("How does MobileNetV2 and the classifier work after a scan?")
    assert "128-value" in knowledge
    assert "class-balanced RBF SVM" in knowledge
    assert "168 values" in knowledge
    assert "does not calculate WHO z-scores" in knowledge


def test_metrics_retrieval_uses_one_report_and_calls_out_missing_auc():
    knowledge, _ = retrieve_knowledge("How reliable is the model? What is its macro F1 and AUC?")
    assert "0.4623" in knowledge
    assert "321 children" in knowledge
    assert "Multiclass ROC-AUC is not reported" in knowledge


def test_who_answer_includes_primary_references_and_separates_app_labels():
    knowledge, sources = retrieve_knowledge("Explain WHO stunting and the 5 to 19 reference")
    assert "birth to 5 years" in knowledge
    assert "ages 5–19 years" in knowledge
    assert "below -2 SD" in knowledge
    assert "does not calculate WHO z-scores" in knowledge
    assert any("questions-and-answers/item/child-growth-standards" in source.url for source in sources)


